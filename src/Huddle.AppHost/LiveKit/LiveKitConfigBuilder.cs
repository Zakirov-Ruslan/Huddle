using System.Net;
using System.Net.Sockets;
using System.Text;

namespace Huddle.AppHost.LiveKit;

/// <summary>
/// Builds the LiveKit container configuration from <see cref="LiveKitOptions"/>.
/// </summary>
/// <remarks>
/// The configuration is passed to the container through the <c>LIVEKIT_CONFIG</c> environment
/// variable (<c>--config-body</c>). Values like <c>rtc.node_ip</c> or <c>rtc.ips</c> have no
/// command line or environment variable equivalent, so the body is the only way to supply them
/// without keeping a machine specific file in the repository.
/// Reference: https://github.com/livekit/livekit/blob/master/config-sample.yaml
/// </remarks>
internal static class LiveKitConfigBuilder
{
    private static readonly TimeSpan NodeIpDetectionTimeout = TimeSpan.FromSeconds(3);

    /// <summary>Renders the configuration for the LiveKit container.</summary>
    /// <param name="options">Values bound from the LiveKit section of the AppHost configuration.</param>
    /// <param name="allowPublicIpDetection">
    /// Whether the public address may be detected with a network request, enabled for the development environment only.
    /// </param>
    public static string Build(LiveKitOptions options, bool allowPublicIpDetection)
    {
        var nodeIp = ResolveNodeIp(options, allowPublicIpDetection);
        var config = new StringBuilder();

        config.AppendLine("# Generated by Huddle.AppHost on every run - do not edit by hand.");
        config.AppendLine("# Override the values with the LiveKit section of the AppHost configuration,");
        config.AppendLine("# e.g. user secrets or the LiveKit__NodeIp environment variable.");
        config.AppendLine("port: 7880");
        config.AppendLine("bind_addresses:");
        config.AppendLine("  - \"\"");
        config.AppendLine("rtc:");
        config.AppendLine("  tcp_port: 7881");
        config.AppendLine("  port_range_start: 50000");
        config.AppendLine("  port_range_end: 60000");
        config.AppendLine("  enable_loopback_candidate: false");

        if (nodeIp is not null)
        {
            config.AppendLine("  # Advertise the public address of the developer machine, otherwise clients outside");
            config.AppendLine("  # the local network only receive private candidates. Port forwarding on the router");
            config.AppendLine("  # is required for the RTC ports.");
            config.AppendLine("  use_external_ip: false");
            config.AppendLine($"  node_ip: {nodeIp}");
        }
        else
        {
            config.AppendLine("  # No public address configured or detected - let LiveKit resolve it with STUN.");
            config.AppendLine("  use_external_ip: true");
        }

        // ICE fallback for networks where direct UDP connectivity is blocked.
        config.AppendLine("  turn_servers:");
        config.AppendLine("    - host: turn.bistri.com");
        config.AppendLine("      port: 80");
        config.AppendLine("      protocol: udp");
        config.AppendLine("      username: \"homeo\"");
        config.AppendLine("      credential: \"homeo\"");

        return config.ToString();
    }

    private static string? ResolveNodeIp(LiveKitOptions options, bool allowPublicIpDetection)
    {
        if (!string.IsNullOrWhiteSpace(options.NodeIp))
        {
            var configured = options.NodeIp.Trim();
            Log($"rtc.node_ip = {configured} (from configuration)");

            return configured;
        }

        if (!allowPublicIpDetection || !options.AutoDetectNodeIp || string.IsNullOrWhiteSpace(options.NodeIpEchoUrl))
        {
            Log("rtc.node_ip is not configured and auto detection is disabled, falling back to use_external_ip");

            return null;
        }

        var detected = DetectPublicIp(options.NodeIpEchoUrl);
        if (detected is null)
        {
            Log("public IP address could not be detected, falling back to use_external_ip");

            return null;
        }

        Log($"rtc.node_ip = {detected} (detected via {options.NodeIpEchoUrl})");

        return detected;
    }

    private static string? DetectPublicIp(string echoUrl)
    {
        try
        {
            using var client = new HttpClient { Timeout = NodeIpDetectionTimeout };
            var response = client.GetStringAsync(echoUrl).GetAwaiter().GetResult().Trim();

            if (IPAddress.TryParse(response, out var address) && address.AddressFamily == AddressFamily.InterNetwork)
                return address.ToString();

            Log($"unexpected response from {echoUrl}: '{response}'");

            return null;
        }
        catch (Exception exception)
        {
            Log($"request to {echoUrl} failed: {exception.Message}");

            return null;
        }
    }

    private static void Log(string message) => Console.WriteLine($"[livekit] {message}");
}
